class Command(BaseCommand):
    help = "Seed mock legislation for the reporting POC"

    def handle(self, *args, **options):
        created = 0
        updated = 0
        for row in SEED:
            obj, was_created = Legislation.objects.update_or_create(
                code=row["code"],
                defaults={k: v for k, v in row.items() if k != "code"},
            )
            if was_created:
                created += 1
            else:
                updated += 1
        self.stdout.write(
            self.style.SUCCESS(
                f"Seed complete: {created} created, {updated} updated "
                f"({Legislation.objects.count()} total)."
            )
        )
